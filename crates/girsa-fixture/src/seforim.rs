/// A jagged schema node, the common case — 5,493 of Sefaria's 6,595.
fn jagged(
    depth: usize,
    address_types: &[&str],
    he_sections: &[&str],
    lengths: Vec<usize>,
) -> Value {
    json!({
        "nodeType": "JaggedArrayNode",
        "depth": depth,
        "addressTypes": address_types,
        "heSectionNames": he_sections,
        "lengths": lengths,
    })
}

/// One Sefaria work, with the fields most of them share already filled in.
fn sefer(slug: &str, he: &str, en: &str, categories: &[&str], body: Body) -> Sefer {
    Sefer {
        slug: slug.to_string(),
        he: he.to_string(),
        en: en.to_string(),
        categories: categories.iter().map(|c| (*c).to_string()).collect(),
        era: None,
        comp_date: None,
        author: None,
        base: Vec::new(),
        variants: Vec::new(),
        body,
    }
}

impl Sefer {
    fn dated(mut self, era: &str, comp_date: &str) -> Self {
        self.era = Some(era.to_string());
        self.comp_date = Some(comp_date.to_string());
        self
    }

    fn on(mut self, base: &str) -> Self {
        self.base.push(base.to_string());
        self
    }

    fn also_called(mut self, variant: &str) -> Self {
        self.variants.push(variant.to_string());
        self
    }

    fn by(mut self, author: &str) -> Self {
        self.author = Some(author.to_string());
        self
    }
}

/// A Sefaria body: a schema, the text it describes, and the edition it is.
fn text(schema: Value, text: Value, he_sections: &[&str], edition: &str) -> Body {
    Body::Sefaria {
        schema,
        text,
        he_sections: he_sections.iter().map(|s| (*s).to_string()).collect(),
        edition: edition.to_string(),
    }
}

/// `n` empty sections, for holding an address open without inventing a text.
fn blanks(n: usize) -> Vec<Value> {
    vec![json!([]); n]
}

/// A flat array of amudim from `1a`, with `at` filled in.
///
/// Sefaria stores a masechta this way, so index 0 is daf 1a — which does not
/// exist — and index 2 is daf 2a, where every masechta begins. Read as an
/// integer every daf in Shas is off by a page and a half, which is exactly what
/// `berakhot_begins_at_daf_2a_and_not_at_daf_1` is about.
fn amudim(pages: usize, at: &[(usize, Value)]) -> Value {
    let mut out = blanks(pages);
    for (i, lines) in at {
        out[*i] = lines.clone();
    }
    Value::Array(out)
}

/// The index of a daf and amud in that flat array. `2a` is 2, `59b` is 117.
fn daf(number: usize, amud: char) -> usize {
    (number - 1) * 2 + usize::from(amud == 'b')
}

