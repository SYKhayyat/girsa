/// One of the seven mefarshim printed around a chumash, all the same shape.
fn commentary_on_genesis(
    slug: &str,
    he: &str,
    en: &str,
    era: &str,
    comp_date: &str,
    first: &str,
) -> Sefer {
    sefer(
        slug,
        he,
        en,
        &["Tanakh", "Rishonim on Tanakh"],
        text(
            jagged(
                3,
                &["Perek", "Pasuk", "Integer"],
                &["פרק", "פסוק", ""],
                vec![1, 1, 1],
            ),
            json!([[[first]]]),
            &["פרק", "פסוק", ""],
            "Vilna Edition",
        ),
    )
    .dated(era, comp_date)
    .on("genesis")
}

/// The one work whose source file this crate rewrites, for the re-import tests.
///
/// Orach Chayim with **a se'if inserted at the front of siman 1** — which is the
/// case spec.md §3 is written about and the case that renumbered 4,170 segments
/// the last time it happened. Handed to [`reimport`], it exercises
/// `continuity::align` and the redirect table on a shelf a test can build.
#[must_use]
pub fn orach_chayim_with_a_seif_inserted() -> Sefer {
    let mut sefer = shelf()
        .into_iter()
        .find(|s| s.slug == "shulchan-arukh/orach-chayim")
        .expect("orach chayim is on the fixture shelf");
    if let Body::Sefaria { text, schema, .. } = &mut sefer.body {
        if let Some(simanim) = text.as_array_mut() {
            if let Some(first) = simanim.first_mut().and_then(Value::as_array_mut) {
                first.insert(
                    0,
                    json!("הַמַּשְׁכִּים לְהִתְחַנֵּן לִפְנֵי בּוֹרְאוֹ יְכַוֵּן לְשָׁעוֹת שֶׁמִּשְׁתַּנּוֹת בָּהֶן הַמִּשְׁמָרוֹת"),
                );
            }
        }
        // The schema says one more se'if, because upstream would say so too.
        schema["lengths"] = json!([58, 7]);
    }
    sefer
}
